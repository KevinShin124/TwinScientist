# ============================================================
# BENCHMARK SCENARIOS
# ============================================================

@dataclass
class CausalPair:
    """A single causal relationship to verify."""
    cause: str
    effect: str
    expected_sign: str          # "positive" | "negative" | "none"
    label: str = ""


@dataclass
class BenchmarkScenario:
    """One benchmark scenario with known ground truth."""
    id: str
    name: str
    description: str
    causal_pairs: List[CausalPair]
    # Null pairs — relationships that SHOULD NOT be detected
    null_pairs: List[Tuple[str, str]] = field(default_factory=list)
    # Data generation parameters
    n_subjects: int = 2
    n_days: int = 14
    seed: int = 42
    # For weak-effect scenarios
    weak_effect: bool = False


def _cp(cause: str, effect: str, sign: str, label: str = "") -> CausalPair:
    """Shorthand to create a CausalPair."""
    return CausalPair(cause=cause, effect=effect, expected_sign=sign,
                      label=label or f"{cause} → {effect}")


